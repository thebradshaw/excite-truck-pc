# Write MKW_REGION_RANGE(ExciteTruck, ...) rows: one per Mario Kart Wii SDK function that has an
# Excite Truck counterpart. Exact-size matches map the whole function body (so addresses inside it,
# such as switch-case labels, follow); other matches map only the entry point.
import json,re,sys
mapping=json.load(open(sys.argv[1])); mkmap=sys.argv[2]
mk=[]
for l in open(mkmap):
    p=l.split(None,1)
    if len(p)==2: mk.append((int(p[0],16),p[1].strip()))
mk.sort()
frag=re.compile(r'_(switch|caseD_[0-9A-Fa-f]+|default)$')
ends={}
starts=[a for a,n in mk if not frag.search(n)]
for a,b in zip(starts,starts[1:]): ends[a]=b-1
rows=[]
for k,v in mapping.items():
    a=int(k,16); e,exact=v if isinstance(v,list) else (v,True)
    last=ends.get(a,a+3) if exact else a+3
    rows.append((a,last,e-a))
rows.sort()
out=[]; prev=-1
for a,last,d in rows:
    if a<=prev: continue
    out.append('MKW_REGION_RANGE(ExciteTruck, %08X, %08X, %s0x%X)'%(a,last,'-' if d<0 else '+',abs(d))); prev=last
print('// Excite Truck (REXE01). Generated by tools/gen_et_versions.py from the SDK function alignment.')
print('\n'.join(out))
print(len(out),'rows',file=sys.stderr)
